/// Подбирает значок по тексту подписи (когда AI не задал значок).
String guessIcon(String text) {
  final t = text.toLowerCase();
  for (final i in kIcons) {
    if (i.words.any(t.contains)) return i.key;
  }
  return 'bolt';
}
